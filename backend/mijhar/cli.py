import sys
from pathlib import Path

from .config import CONFIG_A, CONFIG_B, ROOT, env, sha256_hex


def init_env(force: bool = False, openrouter_key: str | None = None) -> None:
    p = ROOT / ".env"
    if p.exists() and not force:
        print(f"{p} exists; use --force to overwrite", file=sys.stderr)
        sys.exit(1)
    secret, rkey, ckey = secrets.token_hex(32), secrets.token_urlsafe(24), secrets.token_urlsafe(24)
    p.write_text(
        "# Generated by `mijhar init-env`. Git-ignored. Never commit.\n"
        f"MIJHAR_SIGNING_SECRET={secret}\n"
        f"MIJHAR_REVIEWERS=eng.demo:{sha256_hex(rkey)}\n"
        f"MIJHAR_CLIENT_KEYS=ui:{sha256_hex(ckey)}\n"
        "# Local DEMO convenience only (plaintext keys so `mijhar demo` can sign as the demo reviewer):\n"
        f"MIJHAR_DEMO_REVIEWER=eng.demo\nMIJHAR_DEMO_REVIEWER_KEY={rkey}\nMIJHAR_DEMO_CLIENT_KEY={ckey}\n"
        "# Real model + real embeddings (OpenRouter). Text leaves the Kingdom: see SECURITY.md.\n"
        + (f"OPENROUTER_API_KEY={openrouter_key}\nMIJHAR_ALLOW_LIVE=1\n" if openrouter_key else "# OPENROUTER_API_KEY=\n# MIJHAR_ALLOW_LIVE=1\n")
        + "# MIJHAR_MODEL=google/gemma-4-31b-it:free\n# MIJHAR_AGENT_MODEL=google/gemma-4-31b-it:free\n# MIJHAR_PIPELINE_LLM=1\n", encoding="utf-8")
    p.chmod(0o600)
    print(f"wrote {p}. Keys are in that file only; nothing was printed.")


def _auditor(use_mcp: bool, live: bool):
    from .graph import Auditor, Runtime
    from .llm import LLM
    from .toolbox import ToolBox
    return Auditor(Runtime(ToolBox(use_mcp), LLM() if live else None))


def resolve_live(live_flag: bool, offline_flag: bool) -> bool:
    """Default = real model when OPENROUTER_API_KEY is set; --offline forces the rules path."""
    if offline_flag:
        return False
    if live_flag and not env("OPENROUTER_API_KEY"):
        raise SystemExit("--live needs OPENROUTER_API_KEY in backend/.env (or use --offline)")
    return bool(env("OPENROUTER_API_KEY"))


def audit(path: str, cfg_name: str, use_mcp: bool, live: bool, approve: bool) -> int:
    from . import signing
    from .config import RunConfig
    from .documents import load_document
    try:
        text = load_document(path)
    except (RuntimeError, ValueError, OSError) as e:
        print(f"cannot read {path}: {e}", file=sys.stderr); return 4
    cfg = RunConfig(**(CONFIG_B if cfg_name == "B" else CONFIG_A).to_dict() | {"use_mcp": use_mcp, "live_llm": live})
    a = _auditor(use_mcp, live)
    if live:
        from .config import OpenRouterSettings
        print(f"model: {OpenRouterSettings().model}  (claim text and passages are sent to OpenRouter, outside the Kingdom)")
    else:
        print("model: none (offline rules-v1). Set OPENROUTER_API_KEY for the real model.")
    s = a.start(text, Path(path).name, cfg)
    print(f"job {s['job_id']}  status={s.get('status')}  risk={s.get('risk_score')}  quarantined={s.get('quarantined')}")
    for t in s.get("threats", []):
        print(f"  threat [{t['severity']}] {t['rule']}: {t['snippet'][:70]!r}")
    for c in s.get("claims", []):
        print(f"  {c['id']} {c['status']:<15} [{c.get('extractor', '?')}/{','.join(sorted({e.get('method', '?').split(':')[0] for e in c.get('evidence', [])})) or '-'}] {c['text'][:70]}")
    if live and a.rt.llm:
        l = a.rt.llm
        print(f"model requests: {l.calls}  ok: {l.ok}  failed: {l.failed}  tokens: {l.tokens}  "
              f"model that answered: {l.model_used or 'NONE'}  api: {l.shape}"
              + (f"  STOPPED: {l.dead}" if l.dead else ""))
        if l.ok == 0:
            print("WARNING: the model never answered. Every claim above came from the offline rules (rules-v1), "
                  f"not from the model. Last error: {l.last_error}", file=sys.stderr)
    if not s.get("awaiting_human"):
        print("stopped before the human gate:", s.get("error")); return 2
    rsha = a.pending_report_hash(s["job_id"])
    ans = "y" if approve else input("Approve and publish certificate? [y/N] ").strip().lower()
    decision = "approve" if ans == "y" else "reject"
    rid, rkey = env("MIJHAR_DEMO_REVIEWER"), env("MIJHAR_DEMO_REVIEWER_KEY")
    if not (rid and rkey):
        print("no demo reviewer configured (run: mijhar init-env)"); return 3
    tok = signing.issue_decision_token(s["job_id"], decision, rid, rkey, rsha)
    f = a.resume(s["job_id"], tok)
    print(f"decision={decision} -> status={f['status']}", json.dumps(f.get("commit") or {}, ensure_ascii=False))
    return 0


def chat(doc: str | None, file: str | None, says: list[str], use_mcp: bool, offline: bool, approve: bool | None) -> int:
    """Terminal session with the agent. Every tool call is printed as it happens; the approval is asked here."""
    from .agent.service import AgentService, ServiceError
    from .graph import Auditor, Runtime
    from .toolbox import ToolBox
    a = Auditor(Runtime(ToolBox(use_mcp)))
    if offline:
        import os
        os.environ["MIJHAR_ALLOW_LIVE"] = "0"
    svc = AgentService.from_env(a)
    caps = svc.capabilities()
    tty = sys.stdout.isatty()
    c = (lambda code, x: f"\033[{code}m{x}\033[0m") if tty else (lambda code, x: x)
    print(c("1", "MIJHAR agent") + f"  planner={caps['planner']} model={caps['model']} tools_over_mcp={caps['mcp']}")
    if caps["planner"] != "llm":
        print(c("33", f"  offline planner: {caps['reason']}"))
    s = svc.new_session("cli")
    if doc:
        print(f"  attached {svc.add_document(s.id, 'cli', sample=doc)['name']}")
    if file:
        from .documents import load_document
        from pathlib import Path
        print(f"  attached {svc.add_document(s.id, 'cli', Path(file).name, load_document(file))['name']}")
    queue = list(says)
    try:
        while True:
            if queue:
                text = queue.pop(0)
                print(c("36", f"\nyou> {text}"))
            elif says:
                break
            else:
                try:
                    text = input(c("36", "\nyou> ")).strip()
                except EOFError:
                    break
                if text in ("", "exit", "quit"):
                    break
            for ev in svc.turn(s.id, "cli", text):
                t = ev["type"]
                if t == "tool_call":
                    print(c("2", f"  -> {ev['name']}({json.dumps(ev['args'], ensure_ascii=False)[:120]})  [{ev['level']}, {ev['transport']}]"))
                elif t == "tool_progress":
                    print(c("2", f"       node {ev['node']}: {ev['status']} {ev['ms']} ms"))
                elif t == "tool_result":
                    print(c("32" if ev["ok"] else "31", f"  <- {ev['name']}: {ev['summary']} ({ev['ms']} ms)"))
                elif t == "blocked_tool":
                    print(c("31", f"  BLOCKED {ev['name']}: {ev['reason']}"))
                elif t == "notice":
                    print(c("33", f"  ! {ev['text']}"))
                elif t == "final":
                    print(("\nsystem> " if ev.get("author") == "harness" else "\nagent> ") + ev["text"])
                elif t == "approval_required":
                    print(c("1", f"\n  APPROVAL REQUIRED  job={ev['job_id']}  risk={ev['risk_score']}/100  report={ev['report_sha256'][:16]}..."))
                    for x in ev["claims"]:
                        print(f"    {x['id']} {x['status']:<15} {x['text'][:80]}")
                elif t == "done":
                    u = ev["usage"]
                    print(c("2", f"  [{ev['reason']}] model_calls={u['model_calls']} tool_calls={u['tool_calls']} est_tokens={u['tokens']} planner={ev['planner']}"))
            v = svc.view(s.id, "cli")
            if v["pending"]:
                p = v["pending"]
                ans = ("y" if approve else "n") if approve is not None else input("  Sign and publish? [y=approve / n=reject / r=revise] ").strip().lower()
                decision = {"y": "approve", "r": "revise"}.get(ans, "reject")
                rid, rkey = env("MIJHAR_DEMO_REVIEWER"), env("MIJHAR_DEMO_REVIEWER_KEY")
                if not (rid and rkey):
                    print("no demo reviewer configured (run: mijhar init-env)"); return 3
                try:
                    for ev in svc.decide(s.id, "cli", rid, rkey, decision, p["report_sha256"]):
                        if ev["type"] == "decision":
                            print(c("1", f"  decision={ev['decision']} status={ev['status']} tx={ev.get('tx_hash') or '-'}"))
                        elif ev["type"] == "final":
                            print("\nsystem> " + ev["text"])
                except ServiceError as e:
                    print(c("31", f"  refused: {e.message}"))
    finally:
        a.rt.toolbox.close()
    return 0


def main() -> None:
    ap = argparse.ArgumentParser(prog="mijhar")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("init-env"); p.add_argument("--force", action="store_true"); p.add_argument("--openrouter-key")
    p = sub.add_parser("demo"); p.add_argument("--yes", action="store_true"); p.add_argument("--mcp", action="store_true")
    p.add_argument("--live", action="store_true"); p.add_argument("--offline", action="store_true")
    p.add_argument("--config", default="B", choices=["A", "B"])
    p.add_argument("--doc", default="ai_ethics_draft")
    p = sub.add_parser("audit"); p.add_argument("file"); p.add_argument("--config", default="B", choices=["A", "B"])
    p.add_argument("--mcp", action="store_true"); p.add_argument("--live", action="store_true"); p.add_argument("--offline", action="store_true")
    p.add_argument("--yes", action="store_true")
    p = sub.add_parser("chat"); p.add_argument("--doc", help="bundled sample, e.g. cloud_sovereignty_draft")
    p.add_argument("--file"); p.add_argument("--say", action="append", default=[], help="scripted message (repeatable)")
    p.add_argument("--no-mcp", action="store_true"); p.add_argument("--offline", action="store_true")
    g = p.add_mutually_exclusive_group(); g.add_argument("--yes", action="store_true"); g.add_argument("--no", action="store_true")
    p = sub.add_parser("ask"); p.add_argument("question"); p.add_argument("--doc"); p.add_argument("--file")
    p.add_argument("--no-mcp", action="store_true"); p.add_argument("--offline", action="store_true")
    p = sub.add_parser("eval"); p.add_argument("tasks", nargs="?", default=str(ROOT / "tasks.jsonl"))
    p.add_argument("--config", nargs="+", default=["A", "B"], choices=["A", "B"]); p.add_argument("--trials", type=int, default=1)
    p.add_argument("--offline", action="store_true"); p.add_argument("--no-mcp", action="store_true")
    p.add_argument("--ids", nargs="*"); p.add_argument("--limit", type=int)
    p = sub.add_parser("agent"); p.add_argument("--port", type=int, default=8000)
    p = sub.add_parser("serve"); p.add_argument("--port", type=int, default=8000)
    sub.add_parser("mcp")
    a = ap.parse_args()
    if a.cmd == "init-env":
        init_env(a.force, a.openrouter_key)
    elif a.cmd == "demo":
        doc = Path(__file__).parent / "data" / "benchmarks" / f"{a.doc}.md"
        sys.exit(audit(str(doc), a.config, a.mcp, resolve_live(a.live, a.offline), a.yes))
    elif a.cmd == "audit":
        sys.exit(audit(a.file, a.config, a.mcp, resolve_live(a.live, a.offline), a.yes))
    elif a.cmd == "ask":
        sys.exit(chat(a.doc, a.file, [a.question], not a.no_mcp, a.offline, None))
    elif a.cmd == "eval":
        from .agent.evalkit import run as run_eval
        run_eval(Path(a.tasks), a.config, a.trials, a.offline, not a.no_mcp, a.ids, a.limit)
    elif a.cmd == "chat":
        sys.exit(chat(a.doc, a.file, a.say, not a.no_mcp, a.offline, True if a.yes else (False if a.no else None)))
    elif a.cmd == "agent":
        # Local demo convenience: keys go in the URL FRAGMENT, which browsers never send to a server;
        # the page reads them into memory and removes them from the address bar at once.
        from urllib.parse import urlencode
        frag = {k: v for k, v in (("ck", env("MIJHAR_DEMO_CLIENT_KEY")), ("rid", env("MIJHAR_DEMO_REVIEWER")),
                                  ("rk", env("MIJHAR_DEMO_REVIEWER_KEY"))) if v}
        url = f"http://127.0.0.1:{a.port}/agent/" + (f"#{urlencode(frag)}" if frag else "")
        print(f"Open: {url}\n(local demo only: the link carries the demo keys from backend/.env)")
        import uvicorn
        uvicorn.run("mijhar.api:app", host="127.0.0.1", port=a.port)
    elif a.cmd == "serve":
        import uvicorn
        uvicorn.run("mijhar.api:app", host="127.0.0.1", port=a.port)
    elif a.cmd == "mcp":
        from .mcp_server import main as m
        m()


if __name__ == "__main__":
    main()
